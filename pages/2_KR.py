# pages/1_KR.py

from pathlib import Path
import sys

# ------------------------------------------------------------
# Гарантируем, что корень проекта доступен для импортов,
# независимо от того, как Streamlit запускает страницу.
# ------------------------------------------------------------
ROOT = Path(__file__).resolve().parents[1]

if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

# ------------------------------------------------------------
# Пытаемся загрузить интерфейс объединённой страницы КР.
# Вся визуальная часть должна находиться в ui/pages/kr.py.
# ------------------------------------------------------------
try:
    from ui.pages.kr import render_page
except Exception as exc:  # noqa: BLE001
    import streamlit as st

    st.set_page_config(
        page_title="КР отзывы",
        page_icon="📊",
        layout="wide",
    )

    st.error("Не удалось загрузить интерфейс страницы КР.")
    st.info(
        "Проверь, что создан файл `ui/pages/kr.py` "
        "и в нём есть функция `render_page()`."
    )
    st.exception(exc)
    st.stop()

# ------------------------------------------------------------
# Запускаем интерфейс страницы.
# ------------------------------------------------------------
render_page()
def get_mood_data(mood_name: str) -> dict:
    """Получить данные эмоции по названию."""
    return MOODS.get(mood_name, PAUSE_MOOD)

def get_person_emoji(person: str) -> str:
    """Получить эмодзи участницы."""
    return PERSON_EMOJI.get(person, "🌿")

def get_mood_options() -> list:
    """Список эмоций для selectbox (с эмодзи)."""
    return [f"{data['emoji']} {name}" for name, data in MOODS.items()]

def parse_mood_from_option(option: str) -> str:
    """Извлечь название эмоции из опции selectbox."""
    for name in MOODS:
        if name in option:
            return name
    return list(MOODS.keys())[0]